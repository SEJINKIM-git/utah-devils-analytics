-- 운영 Supabase 스키마 중 마이그레이션이 건드리는 부분의 복제본 (2026-10-23 information_schema 기준).
-- 컬럼·enum·FK(ON DELETE CASCADE 포함)·RLS 정책을 운영과 같게 만든다.

create role anon;
create role authenticated;
create role service_role bypassrls;
grant usage on schema public to anon, authenticated, service_role;

-- Supabase의 auth.role() 흉내: 현재 DB 역할 이름을 돌려준다
create schema auth;
create function auth.role() returns text language sql stable as $$ select current_user::text $$;
grant usage on schema auth to anon, authenticated, service_role;

create type public.decision_type as enum
  ('pitching_change','defensive_alignment','steal_attempt','bunt','hit_and_run','intentional_walk','pinch_hitter','pinch_runner','other');
create type public.decision_outcome as enum ('success','failure','neutral','mixed');
create type public.retrospective_eval as enum ('correct','incorrect','ambiguous','pending');
create type public.leverage_class as enum ('low','medium','high','critical');

create table public.players (
  id integer generated by default as identity primary key,
  number integer not null,
  name text not null,
  is_pitcher boolean,
  created_at timestamp default now()
);

create table public.games (
  id integer generated by default as identity primary key,
  date date not null,
  opponent text not null,
  season text not null,
  created_at timestamp default now(),
  time text, location text, is_home boolean, result text, score_us integer, score_them integer, notes text
);

create table public.batting_stats (
  id integer generated by default as identity primary key,
  player_id integer references public.players(id),
  game_id integer references public.games(id),
  pa integer, ab integer, runs integer, hits integer, doubles integer, triples integer, hr integer,
  rbi integer, bb integer, hbp integer, so integer, sb integer,
  created_at timestamp default now(),
  season text
);

create table public.pitching_stats (
  id integer generated by default as identity primary key,
  player_id integer references public.players(id),
  game_id integer references public.games(id),
  w integer, l integer, sv integer, hld integer, ip numeric, ha integer, runs_allowed integer, er integer,
  bb integer, hbp integer, so integer, hr_allowed integer,
  created_at timestamp default now(),
  season text
);

create table public.ai_reports (
  id integer generated by default as identity primary key,
  player_id integer references public.players(id),
  report_type text not null,
  summary text, strengths text, improvements text, training_plan text,
  generated_at timestamp default now()
);

create table public.lineups (
  id integer generated by default as identity primary key,
  name text not null, batting_order jsonb not null, season text,
  game_id integer references public.games(id) on delete set null,
  created_at timestamptz default now(), updated_at timestamptz default now()
);

create table public.roster_uploads (
  id uuid primary key default gen_random_uuid(),
  filename text not null, player_count integer, added_count integer, updated_count integer,
  source text, players_snapshot text, uploaded_at timestamptz default now()
);

create table public.situations (
  id uuid primary key default gen_random_uuid(),
  game_id integer references public.games(id) on delete cascade,
  season text not null, inning smallint not null, inning_half text not null, base_state smallint not null,
  out_count smallint not null, score_us smallint not null, score_them smallint not null,
  score_diff smallint, batter_id integer, pitcher_id integer, context_note text,
  leverage_index numeric,
  leverage_class public.leverage_class not null default 'medium',
  logged_by text,
  logged_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

create table public.game_decisions (
  id uuid primary key default gen_random_uuid(),
  situation_id uuid not null references public.situations(id) on delete cascade,
  game_id integer references public.games(id) on delete cascade,
  season text not null,
  decision_type public.decision_type not null,
  decision_summary text not null,
  rationale text,
  retrospective_eval public.retrospective_eval not null default 'pending',
  logged_by text,
  logged_at timestamptz not null default now(), updated_at timestamptz not null default now()
);

-- 운영의 레버리지 계산 함수와 같은 시그니처 (값은 고정 — 콘솔 RPC가 호출 가능한지만 확인)
create function public.calculate_leverage(p_inning smallint, p_out_count smallint, p_score_diff smallint, p_base_state smallint)
returns table(li numeric, lc public.leverage_class) language sql as $$
  select 1.0::numeric, 'medium'::public.leverage_class
$$;

grant all on all tables in schema public to anon, authenticated, service_role;

-- 운영과 같은 RLS 상태
alter table public.players        enable row level security;
alter table public.batting_stats  enable row level security;
alter table public.pitching_stats enable row level security;
alter table public.games          enable row level security;
alter table public.ai_reports     enable row level security;
alter table public.lineups        enable row level security;
alter table public.roster_uploads enable row level security;
alter table public.situations     enable row level security;
alter table public.game_decisions enable row level security;

create policy allow_delete_players  on public.players        for delete to public using (true);
create policy allow_delete_batting  on public.batting_stats  for delete to public using (true);
create policy allow_delete_pitching on public.pitching_stats for delete to public using (true);
create policy games_write on public.games for all to public using (true);
create policy games_read  on public.games for select to public using (true);
create policy "public read games" on public.games for select to public using (true);
create policy lineups_write on public.lineups for all to public using (true);
create policy lineups_read  on public.lineups for select to public using (true);
create policy allow_all_roster_uploads on public.roster_uploads for all to public using (true) with check (true);
create policy situations_read_public on public.situations for select to public using (true);
create policy game_decisions_read_public on public.game_decisions for select to public using (true);
